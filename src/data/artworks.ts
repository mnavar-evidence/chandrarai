export function getArtwork(slug: string): Artwork | undefined {
  return artworks.find((a) => a.slug === slug);
}

export function getFeaturedArtworks(): Artwork[] {
  return artworks.filter((a) => a.featured).slice(0, 3);
}

export function getMediums(): string[] {
  return [...new Set(artworks.map((a) => a.medium))].sort();
}

export function getSeriesList(): string[] {
  return [...new Set(artworks.map((a) => a.series))].sort();
}
